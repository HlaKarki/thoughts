public enum ClipboardTypes {
  public static let concealed = "org.nspasteboard.ConcealedType"
  public static let transient = "org.nspasteboard.TransientType"
  public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

  public static func isExcluded(_ types: [String]) -> Bool {
    types.contains { [concealed, transient, autoGenerated].contains($0) }
  }

  public static func isConcealed(_ types: [String]) -> Bool {
    types.contains(concealed)
  }

  public static func isConcealedOrTransient(_ types: [String]) -> Bool {
    types.contains { [concealed, transient].contains($0) }
  }
}
